#!/bin/bash
# Builds the DotClaude Dock app: a macOS .app whose only job is to start
# dotclaude.py (if it isn't already running) and open it in the browser.
#
#   bash make-dock-app.sh                 # -> ~/Applications/DotClaude.app
#   bash make-dock-app.sh --add-to-dock   # also pins it (restarts the Dock)
#   bash make-dock-app.sh /some/dir       # build somewhere else
#
# Re-runnable: the bundle is rebuilt from scratch every time, so fixes go here,
# never into the .app by hand. Modelled on AIHQ's scripts/make-dock-app.sh.
#
# The app accepts --no-browser (AIHQ uses it: `open -a DotClaude --args
# --no-browser`, then opens the page itself).
set -euo pipefail

APP_NAME="DotClaude"
DEST="$HOME/Applications"
ADD_TO_DOCK=0
SKIP_ICON=0   # testing only: build without the macOS icon tools

for arg in "$@"; do
  case "$arg" in
    --add-to-dock) ADD_TO_DOCK=1 ;;
    --skip-icon)   SKIP_ICON=1 ;;
    -*) echo "unknown flag: $arg" >&2; exit 2 ;;
    *)  DEST="$arg" ;;
  esac
done

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PY_APP="$REPO_ROOT/dotclaude.py"
ICON_SVG="$REPO_ROOT/icon.svg"
APP="$DEST/$APP_NAME.app"

[ -f "$PY_APP" ]   || { echo "missing: $PY_APP" >&2; exit 1; }
[ -f "$ICON_SVG" ] || { echo "missing: $ICON_SVG" >&2; exit 1; }

# --- bake the toolchain PATH ------------------------------------------------
# A Dock-launched app gets a bare PATH, so record where python3 and claude
# live on THIS machine. Run this generator from a shell where both work.
PY_BIN="$(command -v python3 || true)"
[ -n "$PY_BIN" ] || { echo "python3 not found on PATH" >&2; exit 1; }
PATH_PREFIX="$(dirname "$PY_BIN")"
CLAUDE_BIN="$(command -v claude || true)"
if [ -n "$CLAUDE_BIN" ]; then
  CLAUDE_DIR="$(dirname "$CLAUDE_BIN")"
  [ "$CLAUDE_DIR" != "$PATH_PREFIX" ] && PATH_PREFIX="$PATH_PREFIX:$CLAUDE_DIR"
else
  echo "note: claude CLI not found — DotClaude will run, but the best-practice review won't."
fi

echo "DotClaude Dock app"
echo "  app source  $PY_APP"
echo "  bundle      $APP"
echo "  baked PATH  $PATH_PREFIX"

mkdir -p "$DEST"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# --- Info.plist -------------------------------------------------------------
# LSUIElement: a launcher, not a window owner, so no lingering second Dock icon.
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>$APP_NAME</string>
  <key>CFBundleDisplayName</key><string>$APP_NAME</string>
  <key>CFBundleIdentifier</key><string>local.dotclaude.launcher</string>
  <key>CFBundleExecutable</key><string>$APP_NAME</string>
  <key>CFBundleIconFile</key><string>$APP_NAME</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.2</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>LSUIElement</key><true/>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

# --- executable -------------------------------------------------------------
cat > "$APP/Contents/MacOS/$APP_NAME" <<WRAP
#!/bin/bash
# GENERATED by make-dock-app.sh — do not edit. Re-run the generator.
export PATH="$PATH_PREFIX:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
PY_APP="$PY_APP"
OPEN="\${DOTCLAUDE_OPEN:-open}"   # overridable for tests only
LOG="\$HOME/Library/Logs/DotClaude/launcher.log"
mkdir -p "\$(dirname "\$LOG")"
BROWSER=1
for a in "\$@"; do [ "\$a" = "--no-browser" ] && BROWSER=0; done

log()   { printf '%s  %s\n' "\$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "\$*" >>"\$LOG"; }
alert() {
  osascript -e 'on run argv' \\
            -e 'display alert "DotClaude did not start" message (item 1 of argv) as critical' \\
            -e 'end run' -- "\$1" >/dev/null 2>&1 || "\$OPEN" -t "\$LOG" >/dev/null 2>&1 || true
}
# Prints the URL of a running DotClaude (ports 8765-8784), or nothing.
find_running() {
  for p in \$(seq 8765 8784); do
    if curl -sf -m 1 "http://127.0.0.1:\$p/health" 2>/dev/null | grep -q '"app": "dotclaude"'; then
      echo "http://127.0.0.1:\$p/"; return 0
    fi
  done
  return 1
}

if [ ! -f "\$PY_APP" ]; then
  alert "DotClaude moved. Expected \$PY_APP. Re-run make-dock-app.sh from its new folder."
  exit 1
fi

URL="\$(find_running || true)"
if [ -z "\$URL" ]; then
  log "starting \$PY_APP"
  nohup python3 "\$PY_APP" --no-browser >>"\$LOG" 2>&1 </dev/null &
  for _ in \$(seq 1 40); do
    sleep 0.5
    URL="\$(find_running || true)"
    [ -n "\$URL" ] && break
  done
fi
if [ -z "\$URL" ]; then
  alert "\$(tail -n 12 "\$LOG")

Full log: \$LOG"
  exit 1
fi
log "running at \$URL"
[ "\$BROWSER" -eq 1 ] && "\$OPEN" "\$URL"
exit 0
WRAP
chmod +x "$APP/Contents/MacOS/$APP_NAME"

# --- icon -------------------------------------------------------------------
if [ "$SKIP_ICON" -eq 1 ]; then
  echo "  icon        skipped (--skip-icon)"
else
  WORK="$(mktemp -d)"
  trap 'rm -rf "$WORK"' EXIT
  if command -v rsvg-convert >/dev/null 2>&1; then
    rsvg-convert -w 1024 -h 1024 "$ICON_SVG" -o "$WORK/icon.png"; RENDERER="rsvg-convert"
  else
    cp "$ICON_SVG" "$WORK/icon.svg"
    qlmanage -t -s 1024 -o "$WORK" "$WORK/icon.svg" >/dev/null 2>&1 || true
    [ -f "$WORK/icon.svg.png" ] || { echo "icon render failed (no rsvg-convert, and qlmanage produced nothing)" >&2; exit 1; }
    mv "$WORK/icon.svg.png" "$WORK/icon.png"; RENDERER="qlmanage"
  fi
  echo "  icon        rendered via $RENDERER"
  ICONSET="$WORK/$APP_NAME.iconset"
  mkdir -p "$ICONSET"
  for s in 16 32 128 256 512; do
    sips -z "$s" "$s" "$WORK/icon.png" --out "$ICONSET/icon_${s}x${s}.png" >/dev/null
    sips -z "$((s*2))" "$((s*2))" "$WORK/icon.png" --out "$ICONSET/icon_${s}x${s}@2x.png" >/dev/null
  done
  iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/$APP_NAME.icns"
  touch "$APP"
  /System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister \
    -f "$APP" >/dev/null 2>&1 || true
fi

echo "  built       $APP"

if [ "$ADD_TO_DOCK" -eq 1 ]; then
  defaults write com.apple.dock persistent-apps -array-add \
    "<dict><key>tile-data</key><dict><key>file-data</key><dict><key>_CFURLString</key><string>$APP</string><key>_CFURLStringType</key><integer>0</integer></dict></dict></dict>"
  killall Dock
  echo "  pinned      added to the Dock (Dock restarted)"
else
  echo "  next        drag $APP into the Dock, or re-run with --add-to-dock"
fi
